const LANG_ORDER = ["es", "en", "fr", "nl", "de", "zh", "ja"];
const DESC_FIELD = {es: "d", en: "d_en", fr: "d_fr", nl: "d_nl", de: "d_de", zh: "d_zh", ja: "d_ja"};

function currentLang(){
  return localStorage.getItem("campingsLang") || "es";
}
function setLang(l){
  localStorage.setItem("campingsLang", l);
}
function t(key){
  const lang = currentLang();
  return (I18N[lang] && I18N[lang][key]) || I18N.es[key] || key;
}
function descFor(c){
  const lang = currentLang();
  const field = DESC_FIELD[lang] || "d";
  return c[field] && c[field].trim() ? c[field] : c.d;
}
